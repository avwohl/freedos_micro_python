import sys
import time
import lwip
import uc386_net
import wget
print('WGETTEST: start')
_ = lwip.reset()
# Static IP for the QEMU SLIRP user-mode network (DHCP retry timer
# inside sys_check_timeouts deterministically hangs under PMODE/W
# for the reason TLSTEST documents — bypass it the same way).
rc = uc386_net.eth_init(False)
uc386_net.eth_set_static('10.0.2.15', '255.255.255.0', '10.0.2.2')
for _ in range(5):
    _ = lwip.callback()
    time.sleep_ms(50)
info = uc386_net.eth_status()
ip = info[0]
up = info[3]
print('WGETTEST: ifup', up, 'ip', ip)
if not up or not ip or ip == '0.0.0.0':
    print('WGETTEST: static_ip_failed')
    sys.exit(1)
# Verified HTTPS download. CA bundle on the floppy at A:TESTCA.PEM
# was generated by run-wget-rig.sh (openssl req -x509 ...) and
# trust-anchors the server's self-signed cert. axtls validates
# the chain via load_verify_locations + verify_mode=CERT_REQUIRED.
print('WGETTEST: pre_fetch')
try:
    status, n_bytes, path = wget.fetch(
        'https://10.0.2.2:8443/wget.bin',
        out='WGETOUT.BIN',
        verify=True,
        ca_certs='TESTCA.PEM',
    )
except OSError as e:
    print('WGETTEST: fetch_failed', e)
    sys.exit(2)
print('WGETTEST: post_fetch status=', status, 'bytes=', n_bytes)
# Sanity: read the file back and check the marker the rig server
# bakes into the body. run-wget-rig.sh writes 'WGET_RIG_OK\n'
# plus a deterministic 256-byte payload.
try:
    f = open('WGETOUT.BIN', 'rb')
    body = f.read()
    f.close()
except OSError as e:
    print('WGETTEST: read_back_failed', e)
    sys.exit(3)
print('WGETTEST: read_back_len', len(body))
# Skip slice — the uc386 bytearray slice path has a known
# IndexError (see TLSTEST notes); substring works on the whole buf.
if b'WGET_RIG_OK' in body and n_bytes == len(body) and len(body) > 11:
    print('WGETTEST: PASS')
else:
    print('WGETTEST: FAIL_unexpected_response n=', n_bytes)
